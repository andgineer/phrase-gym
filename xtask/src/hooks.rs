use std::path::{Path, PathBuf};

use crate::tools::{Failure, Workspace};

const HOOKS: &str = ".githooks";
const FRAMEWORK_MARKER: &str = "File generated by pre-commit";

pub fn install(workspace: &Workspace) -> Result<(), Failure> {
    if !workspace.root.join(HOOKS).join("pre-commit").is_file() {
        return Err(Failure::new(format!("{HOOKS}/pre-commit is missing")));
    }
    let common = workspace.git_output(&["rev-parse", "--git-common-dir"])?;
    let local = workspace.root.join(common.trim()).join("hooks");
    if remove_framework_hook(&local.join("pre-commit"))? {
        println!("xtask: removed the pre-commit framework hook");
    }
    workspace.git_output(&["config", "core.hooksPath", HOOKS])?;
    for bypassed in custom_hooks(&local) {
        println!(
            "xtask: {} is no longer run; move it to {HOOKS}/ to keep it",
            bypassed.display()
        );
    }
    println!("xtask: commits now run {HOOKS}/pre-commit, which runs `cargo xtask pre`");
    Ok(())
}

// The pre-commit framework hook needs Python tooling the project lacks; other hooks stay.
fn remove_framework_hook(path: &Path) -> Result<bool, Failure> {
    let Ok(text) = std::fs::read_to_string(path) else {
        return Ok(false);
    };
    if !text.contains(FRAMEWORK_MARKER) {
        return Ok(false);
    }
    std::fs::remove_file(path)
        .map_err(|error| Failure::new(format!("removing {}: {error}", path.display())))?;
    Ok(true)
}

fn custom_hooks(directory: &Path) -> Vec<PathBuf> {
    let Ok(entries) = std::fs::read_dir(directory) else {
        return Vec::new();
    };
    let mut hooks: Vec<PathBuf> = entries
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.is_file() && path.extension().is_none_or(|ext| ext != "sample"))
        .collect();
    hooks.sort();
    hooks
}

#[cfg(test)]
mod tests {
    #[cfg(unix)]
    use std::os::unix::fs::PermissionsExt;
    use std::process::Command;

    use super::*;

    fn git(root: &Path, arguments: &[&str]) -> std::process::Output {
        Command::new("git")
            .args([
                "-c",
                "user.name=Test",
                "-c",
                "user.email=test@example.invalid",
            ])
            .args(["-c", "commit.gpgsign=false"])
            .args(arguments)
            .current_dir(root)
            .output()
            .unwrap()
    }

    fn repository() -> tempfile::TempDir {
        let root = tempfile::tempdir().unwrap();
        assert!(git(root.path(), &["init", "--quiet"]).status.success());
        std::fs::create_dir(root.path().join(HOOKS)).unwrap();
        std::fs::write(
            root.path().join(HOOKS).join("pre-commit"),
            "#!/bin/sh\nexit 1\n",
        )
        .unwrap();
        root
    }

    #[test]
    fn replaces_only_the_framework_hook_and_selects_the_committed_hooks() {
        let root = repository();
        let local = root.path().join(".git/hooks");
        std::fs::write(
            local.join("pre-commit"),
            format!("#!/usr/bin/env bash\n# {FRAMEWORK_MARKER}: https://pre-commit.com\n"),
        )
        .unwrap();
        std::fs::write(local.join("commit-msg"), "#!/bin/sh\n").unwrap();
        let workspace = Workspace {
            root: root.path().to_path_buf(),
        };
        install(&workspace).unwrap();
        assert!(!local.join("pre-commit").exists());
        assert!(local.join("commit-msg").exists());
        assert_eq!(custom_hooks(&local), [local.join("commit-msg")]);
        install(&workspace).unwrap();
        let configured = git(root.path(), &["config", "core.hooksPath"]);
        assert_eq!(String::from_utf8(configured.stdout).unwrap().trim(), HOOKS);
    }

    #[test]
    fn keeps_a_custom_pre_commit_hook_and_requires_the_committed_one() {
        let root = repository();
        let custom = root.path().join(".git/hooks/pre-commit");
        std::fs::write(&custom, "#!/bin/sh\necho custom\n").unwrap();
        let workspace = Workspace {
            root: root.path().to_path_buf(),
        };
        install(&workspace).unwrap();
        assert!(custom.exists());
        std::fs::remove_file(root.path().join(HOOKS).join("pre-commit")).unwrap();
        assert!(install(&workspace).is_err());
    }

    #[cfg(unix)]
    #[test]
    fn a_commit_runs_the_committed_hook() {
        let root = repository();
        let hook = root.path().join(HOOKS).join("pre-commit");
        std::fs::set_permissions(&hook, std::fs::Permissions::from_mode(0o755)).unwrap();
        std::fs::write(root.path().join("file.txt"), "text\n").unwrap();
        assert!(git(root.path(), &["add", "file.txt"]).status.success());
        let commit = ["commit", "--quiet", "-m", "test"];
        assert!(git(root.path(), &commit).status.success());
        install(&Workspace {
            root: root.path().to_path_buf(),
        })
        .unwrap();
        std::fs::write(root.path().join("file.txt"), "changed\n").unwrap();
        assert!(git(root.path(), &["add", "file.txt"]).status.success());
        assert!(!git(root.path(), &commit).status.success());
    }
}
